CREATE TABLE IF NOT EXISTS lead
(
  id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
  name character varying(255) COLLATE pg_catalog."default" NOT NULL,
  phone character varying(255) COLLATE pg_catalog."default" NOT NULL,
  message character varying(1000) COLLATE pg_catalog."default" DEFAULT NULL::character varying,
  created_at timestamp(0) without time zone NOT NULL,
  ip character varying(255) COLLATE pg_catalog."default" NOT NULL,
  user_agent character varying(255) COLLATE pg_catalog."default" NOT NULL,
  source_url character varying(500) COLLATE pg_catalog."default" NOT NULL,
  CONSTRAINT lead_pkey PRIMARY KEY (id)
);
